#!/usr/bin/env node
// Writes the validator's MANUAL_RULES into every skill's standalone section,
// between the rules markers, so checking by hand and the validator enforce
// the same rules. Run after changing MANUAL_RULES; a test fails until you do.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { MANUAL_RULES } from '../skills/dybs-start/scripts/dybs-validate.mjs';
import { SKILLS_SRC, skillNames } from '../src/update.mjs';

export const START = '<!-- rules:start (generated by scripts/sync-rules.mjs, do not edit) -->';
export const END = '<!-- rules:end -->';
export const rulesBlock = () => [START, ...MANUAL_RULES.map((r, i) => `${i + 1}. ${r.text}`), END].join('\n');

if (process.argv[1] && process.argv[1].endsWith('sync-rules.mjs')) {
  let changed = 0;
  for (const s of skillNames()) {
    const p = join(SKILLS_SRC, s, 'SKILL.md');
    const t = readFileSync(p, 'utf8');
    const a = t.indexOf(START);
    const b = t.indexOf(END);
    if (a < 0 || b < 0) continue;
    const next = t.slice(0, a) + rulesBlock() + t.slice(b + END.length);
    if (next !== t) { writeFileSync(p, next); changed++; }
  }
  console.log(changed ? `Updated the rules in ${changed} skill(s).` : 'Rules are in sync.');
}
