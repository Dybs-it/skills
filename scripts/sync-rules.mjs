#!/usr/bin/env node
// Keeps generated text in the skills in step with its single source:
// - the validator's MANUAL_RULES go into every skill's standalone section;
// - each doc skill's "Readiness checklist" goes into dybs-check, so a
//   dybs-check installed on its own can still check readiness.
// Run after changing either source; a test fails until you do.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { MANUAL_RULES, ORDER } from '../skills/dybs-start/scripts/dybs-validate.mjs';
import { SKILLS_SRC, skillNames } from '../src/update.mjs';

export const START = '<!-- rules:start (generated by scripts/sync-rules.mjs, do not edit) -->';
export const END = '<!-- rules:end -->';
export const CL_START = '<!-- checklists:start (generated by scripts/sync-rules.mjs, do not edit) -->';
export const CL_END = '<!-- checklists:end -->';

export const rulesBlock = () => [START, ...MANUAL_RULES.map((r, i) => `${i + 1}. ${r.text}`), END].join('\n');

// The text between "## Readiness checklist" and the next "## " heading.
export function checklistOf(skill) {
  const p = join(SKILLS_SRC, skill, 'SKILL.md');
  if (!existsSync(p)) return null; // project.md has no skill of its own
  const t = readFileSync(p, 'utf8');
  const m = t.match(/^## Readiness checklist\n([\s\S]*?)(?=^## )/m);
  return m ? m[1].trim() : null;
}

export function checklistsBlock() {
  const parts = [CL_START];
  for (const doc of ORDER) {
    const c = checklistOf(`dybs-${doc}`);
    if (!c) continue;
    parts.push(`### ${doc}\n\n${c.replace(/^\*\*(core|thorough)\*\*$/gm, '*$1*')}`);
  }
  parts.push(CL_END);
  return parts.join('\n\n');
}

function replaceBetween(text, start, end, block) {
  const a = text.indexOf(start);
  const b = text.indexOf(end);
  if (a < 0 || b < 0) return text;
  return text.slice(0, a) + block + text.slice(b + end.length);
}

if (process.argv[1] && process.argv[1].endsWith('sync-rules.mjs')) {
  let changed = 0;
  for (const s of skillNames()) {
    const p = join(SKILLS_SRC, s, 'SKILL.md');
    const t = readFileSync(p, 'utf8');
    let next = replaceBetween(t, START, END, rulesBlock());
    next = replaceBetween(next, CL_START, CL_END, checklistsBlock());
    if (next !== t) { writeFileSync(p, next); changed++; }
  }
  console.log(changed ? `Updated generated text in ${changed} skill(s).` : 'Generated text is in sync.');
}
